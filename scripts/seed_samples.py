"""Rebuilds the demo sample library in data/samples.

Downloads two Creative Commons bird recordings from Wikimedia Commons (originally xeno-canto),
trims them to their best 12 seconds, and generates a synthetic wind clip that demos the
"no bird detected" path. Needs internet once; the app itself never does.

Usage: python scripts/seed_samples.py
"""

import json
import tempfile
import urllib.request
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy.signal import butter, sosfiltfilt

SAMPLES_DIR = Path(__file__).resolve().parent.parent / "data" / "samples"
USER_AGENT = "forest-symphony/0.1 (sample seeding script)"

BIRD_SAMPLES = [
    {
        "id": "morning-robin",
        "title": "Morning Robin Chirp",
        "description": "An American Robin's cheerful carolling song.",
        "url": "https://upload.wikimedia.org/wikipedia/commons/d/d3/Turdus_migratorius_-_American_Robin_XC130246.ogg",
        "source_page": "https://commons.wikimedia.org/wiki/File:Turdus_migratorius_-_American_Robin_XC130246.ogg",
        "credit": "Jonathon Jongsma (xeno-canto XC130246)",
        "license": "CC BY-SA 3.0",
        "start_s": 9.0,
    },
    {
        "id": "deep-woods-owl",
        "title": "Deep Woods Owl",
        "description": "A Tawny Owl hooting in a dark European forest.",
        "url": "https://upload.wikimedia.org/wikipedia/commons/3/3f/Strix_aluco_-_Tawny_Owl_XC603209.mp3",
        "source_page": "https://commons.wikimedia.org/wiki/File:Strix_aluco_-_Tawny_Owl_XC603209.mp3",
        "credit": "Benoît Van Hecke (xeno-canto XC603209)",
        "license": "CC BY-SA 4.0",
        "start_s": 1.0,
    },
]
CLIP_SECONDS = 12.0


def _download(url: str, dest: Path) -> Path:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=60) as response:
        dest.write_bytes(response.read())
    return dest


def _write_clip(samples: np.ndarray, sample_rate: int, name: str) -> str:
    filename = f"{name}.flac"
    sf.write(SAMPLES_DIR / filename, samples, sample_rate, subtype="PCM_16")
    return filename


def _make_wind(sample_rate: int = 48_000, seconds: float = 8.0) -> np.ndarray:
    """Low rumbling noise with slow gusts, like wind hitting a phone microphone."""
    rng = np.random.default_rng(42)
    noise = rng.standard_normal(int(sample_rate * seconds))
    rumble = sosfiltfilt(butter(4, 300, btype="lowpass", fs=sample_rate, output="sos"), noise)
    t = np.arange(len(noise)) / sample_rate
    gusts = 0.6 + 0.4 * np.sin(2 * np.pi * 0.3 * t) * np.sin(2 * np.pi * 0.07 * t)
    wind = rumble * gusts
    return (wind / np.max(np.abs(wind)) * 0.6).astype(np.float32)


def main() -> None:
    SAMPLES_DIR.mkdir(parents=True, exist_ok=True)
    catalog = []
    with tempfile.TemporaryDirectory() as tmp:
        for spec in BIRD_SAMPLES:
            source = _download(spec["url"], Path(tmp) / Path(spec["url"]).name)
            samples, sample_rate = sf.read(source, dtype="float32", always_2d=True)
            mono = samples.mean(axis=1)
            start = int(spec["start_s"] * sample_rate)
            clip = mono[start : start + int(CLIP_SECONDS * sample_rate)]
            filename = _write_clip(clip, sample_rate, spec["id"])
            catalog.append(
                {k: spec[k] for k in ("id", "title", "description", "source_page", "credit", "license")}
                | {"file": filename}
            )
            print(f"wrote {filename}")

    catalog.append(
        {
            "id": "windy-ridge",
            "title": "Windy Ridge (no bird)",
            "description": "Just wind. Shows how the app responds when no bird is heard.",
            "source_page": None,
            "credit": "Generated by scripts/seed_samples.py",
            "license": "Public domain",
            "file": _write_clip(_make_wind(), 48_000, "windy-ridge"),
        }
    )
    (SAMPLES_DIR / "samples.json").write_text(json.dumps(catalog, indent=2, ensure_ascii=False) + "\n")
    print("wrote samples.json")


if __name__ == "__main__":
    main()
